#!/usr/bin/env python3
"""CUBI knowledge base: concatenation, drift check, AI-guided digest update.

The knowledge base (KB) is the git submodule cubi-rules/knowledge-base.wiki.
Two things are derived from it:
    1. {rules,tech,hints}-kb-agents-instructions.md: plain concatenations of the
       KB pages, written by every deploy-configs to ~/.config/opencode/cubi-kb/ (agents
       read them on demand). Fully automatic.
    2. cubi-rules/cubi-rules-condensed.md: the hand-curated digest loaded into
       every agent. It is derived by an AI from the KB; cubi-rules/kb-source.json
       records the KB commit it was last derived from, so a KB update shows up
       as drift and 'update-cubi-digest' generates the prompt to re-derive it.

Run codebase/opencode-kit.py instead of this file.
"""

import datetime
import subprocess
import sys

from .common import (
    BUILD,
    CUBI,
    DIGEST,
    KB_SOURCE,
    KB_WIKI,
    REPO,
    die,
    ensure_submodules,
    find_opencode,
    git,
    info,
    load_json,
    render,
    require_v2,
    warn,
    write_atomic,
)

CATEGORIES = ("rules", "tech", "hints")
SKIP = {"_Sidebar.md", "_Footer.md", "Home.md"}
PROMPT_FILE = BUILD / "cubi-digest-update-prompt.md"
MAX_DIFF_CHARS = 60000
KB_URL = "https://github.com/core-unit-bioinformatics/knowledge-base/wiki"


def kb_head():
    """(full commit, ISO date) of the checked-out KB submodule."""
    ensure_submodules(("kb",))
    line = git(["log", "-1", "--format=%H %cs"], cwd=KB_WIKI)
    commit, date = line.split()
    return commit, date


def read_source():
    """Contents of cubi-rules/kb-source.json (stop with a fix if missing)."""
    if not KB_SOURCE.is_file():
        die(f"{KB_SOURCE}: missing; run 'codebase/opencode-kit.py mark-cubi-digest-synced' once the digest matches the KB")
    return load_json(KB_SOURCE)


def render_concat():
    """{file name: text} of the three KB concatenations; writes nothing."""
    commit, date = kb_head()
    texts = {}
    for cat in CATEGORIES:
        # every .md below <wiki>/<cat>/, minus the wiki navigation pages
        files = sorted(p for p in (KB_WIKI / cat).rglob("*.md") if p.name not in SKIP)
        if not files:
            die(f"{KB_WIKI / cat}: no .md files found; is the submodule checked out?")
        header = (
            f"<!-- Generated by codebase/opencode-kit.py from the CUBI knowledge base "
            f"({KB_URL}), commit {commit[:7]} of {date}. Do not edit. -->\n"
        )
        parts = [p.read_text(encoding="utf-8").rstrip() + "\n" for p in files]
        texts[f"{cat}-kb-agents-instructions.md"] = header + "\n" + "\n".join(parts)
    return texts


def write_concat(out_dir, texts):
    """Write rendered KB concatenations (render_concat) into out_dir; return the file paths."""
    written = []
    for name, text in texts.items():
        out = out_dir / name
        write_atomic(out, text)
        written.append(out)
    info(f"wrote KB concatenations ({', '.join(CATEGORIES)}) into {out_dir}")
    return written


def concat(out_dir):
    """Write the three KB concatenations into out_dir; return the file paths."""
    return write_concat(out_dir, render_concat())


def _has_commit(commit):
    """True when the KB submodule has `commit` locally."""
    res = subprocess.run(["git", "cat-file", "-e", f"{commit}^{{commit}}"], cwd=KB_WIKI, capture_output=True)
    return res.returncode == 0


def drift(fetch=True):
    """(recorded commit, current commit, changed KB paths) of the digest's source.

    The recorded commit must exist locally to diff against it. With fetch, a missing
    commit is fetched from origin (network); without fetch (deploy), changed is None
    and a WARNING says the comparison is not possible.
    """
    source = read_source()
    old = source["derived_from_commit"]
    new, _ = kb_head()
    if old == new:
        return old, new, []
    if not _has_commit(old):
        if not fetch:
            warn(
                f"cannot compare the CUBI digest (KB {old[:7]}) with the KB ({new[:7]}): commit "
                f"{old[:7]} is not in the local submodule; run: codebase/opencode-kit.py check-cubi-digest --fetch"
            )
            return old, new, None
        git(["fetch", "--quiet", "origin"], cwd=KB_WIKI)
    changed = git(["diff", "--name-only", old, new, "--", *CATEGORIES], cwd=KB_WIKI).splitlines()
    return old, new, changed


def status(fetch=False):
    """Print whether the digest matches the checked-out KB (and upstream with fetch)."""
    old, new, changed = drift()
    source = read_source()
    print(f"Digest:        {DIGEST.relative_to(REPO)}")
    print(f"Derived from:  KB {old[:7]} ({source.get('kb_commit_date', '?')}), digest updated {source.get('derived_on', '?')}")
    print(f"Checked out:   KB {new[:7]} ({kb_head()[1]})")
    if fetch:
        git(["fetch", "--quiet", "origin"], cwd=KB_WIKI)
        ahead = git(["rev-list", "--count", "HEAD..origin/HEAD"], cwd=KB_WIKI, check=False) or "?"
        print(f"Upstream:      {ahead} newer commit(s) on origin" + (" -> codebase/opencode-kit.py update-git-submodules" if ahead not in ("0", "?") else ""))
    if old == new:
        print("Status:        in sync")
        return True
    rule_pages = [c for c in changed if c.startswith("rules/")]
    print(f"Status:        OUT OF SYNC: {len(changed)} KB page(s) changed, {len(rule_pages)} of them rule pages")
    for c in changed:
        print(f"  {c}")
    print("Next:          codebase/opencode-kit.py update-cubi-digest")
    return False


def build_prompt(full=False):
    """Text of the AI prompt that updates the digest to the current KB."""
    old, new, changed = drift()
    new_date = kb_head()[1]
    rules_now = sorted(str(p.relative_to(REPO)) for p in (KB_WIKI / "rules").rglob("*.md") if p.name not in SKIP)
    lines = [
        "# Task: update the CUBI rules digest to the current CUBI knowledge base",
        "",
        f"You work in the repository `{REPO}`. The file `{DIGEST.relative_to(REPO)}` is a short",
        "digest of the CUBI knowledge base (git submodule `cubi-rules/knowledge-base.wiki`, the",
        f"wiki of {KB_URL}). It is loaded into the context of EVERY opencode agent, including",
        "small local models, so it must stay short and precise.",
        "",
    ]
    if full or old == new:
        lines += [
            f"Re-derive the digest from the knowledge base at commit {new[:7]} ({new_date}).",
            "Read every rule page:",
            *[f"- `{p}`" for p in rules_now],
            "",
            "Tech and hints pages (`cubi-rules/knowledge-base.wiki/{tech,hints}/`) are not condensed;",
            "the digest only points to them (see its last section).",
        ]
    else:
        log = git(["log", "--oneline", f"{old}..{new}"], cwd=KB_WIKI)
        rules_diff = git(["diff", old, new, "--", "rules"], cwd=KB_WIKI)
        other = [c for c in changed if not c.startswith("rules/")]
        lines += [
            f"The digest was derived from knowledge-base commit {old[:7]}. The knowledge base is",
            f"now at {new[:7]} ({new_date}). Commits since then:",
            "",
            "```",
            log or "(none)",
            "```",
            "",
            "## Changes to the rule pages (`rules/`)",
            "",
        ]
        if not rules_diff:
            lines.append("None. Only tech/hints pages changed (listed below).")
        elif len(rules_diff) > MAX_DIFF_CHARS:
            lines += [
                f"The diff is too long to include ({len(rules_diff)} characters). Read these changed",
                "pages in full instead:",
                *[f"- `cubi-rules/knowledge-base.wiki/{c}`" for c in changed if c.startswith("rules/")],
            ]
        else:
            lines += ["```diff", rules_diff, "```"]
        lines += ["", "## Changed tech/hints pages (not condensed; the digest only points to them)", ""]
        lines += [f"- `cubi-rules/knowledge-base.wiki/{c}`" for c in other] or ["None."]
    lines += [
        "",
        "## What to do",
        "",
        f"1. Read the current digest `{DIGEST.relative_to(REPO)}` and",
        "   `configs/instructions/general-work-rules.md` (the other global instruction file; don't",
        "   duplicate its content). Where the diff lacks context, read the full page under",
        "   `cubi-rules/knowledge-base.wiki/`.",
        "2. Update the digest so it states the rules as they are NOW: add new rules, change",
        "   changed ones, delete removed ones. Keep only rules that change how an agent acts",
        "   (naming, git and branches, versioning, dates, sample sheets, file types, external",
        "   pipelines, project layout). Never invent a rule that is not in the knowledge base.",
        "3. Keep the existing structure, headings and terse imperative style; stay under about",
        "   60 lines. Keep the closing section that points to",
        "   `~/.config/opencode/cubi-kb/{rules,tech,hints}-kb-agents-instructions.md`.",
        f"4. Edit only `{DIGEST.relative_to(REPO)}`. Do not commit and do not run",
        "   `opencode-kit.py mark-cubi-digest-synced`; the user reviews the change first.",
        "5. End with a short list: each change as `KB page -> digest line`, and anything in the",
        "   knowledge base you deliberately left out and why.",
    ]
    return "\n".join(lines) + "\n"


def update(run=False, model=None, agent="build", full=False):
    """Guide (or with run=True: perform) the AI update of the digest."""
    old, new, changed = drift()
    if old == new and not full:
        info(f"digest is in sync with KB {new[:7]}; nothing to do (use --full to re-derive anyway)")
        return
    PROMPT_FILE.parent.mkdir(parents=True, exist_ok=True)
    PROMPT_FILE.write_text(build_prompt(full=full), encoding="utf-8")
    rel = PROMPT_FILE.relative_to(REPO)
    info(f"wrote the AI prompt to {PROMPT_FILE} ({len(changed)} changed KB page(s))")
    if not run:
        print(
            f"""
How to update the CUBI digest ({DIGEST.relative_to(REPO)}):

  1. Read the prompt:            {rel}
  2. Let an AI apply it, one of:
     a) automatically:           codebase/opencode-kit.py update-cubi-digest --run
                                 (opencode, agent '{agent}', edits only the digest, no commit)
     b) interactively:           cd {REPO} && opencode
                                 then type: Follow the instructions in @{rel}
     c) any other AI chat:       paste the prompt plus the digest and the changed KB pages
  3. Review the result:          git -C {REPO} diff {DIGEST.relative_to(REPO)}
  4. Accept it:                  codebase/opencode-kit.py mark-cubi-digest-synced
                                 git -C {REPO} add {DIGEST.relative_to(REPO)} {KB_SOURCE.relative_to(REPO)} cubi-rules/knowledge-base.wiki
                                 git -C {REPO} commit -m "Update CUBI digest to KB {new[:7]}"
  5. Redeploy:                   codebase/opencode-kit.py deploy-configs <backend>
""",
            file=sys.stderr,
        )
        return
    exe = require_v2(find_opencode())
    before = DIGEST.read_text(encoding="utf-8")
    cmd = [exe, "run", "--agent", agent, "--archived", "--auto", "--title", f"CUBI digest update to KB {new[:7]}"]
    if model:
        cmd += ["--model", model]
    cmd += ["-f", str(PROMPT_FILE), "Follow the instructions in the attached file exactly."]
    info(f"running opencode in {REPO} (agent {agent}{', model ' + model if model else ''}); this can take several minutes")
    # cwd=REPO so the agent's working directory is this repository; output streams to the terminal
    res = subprocess.run(cmd, cwd=REPO)
    if res.returncode != 0:
        die(f"opencode run exited with {res.returncode}; the digest may be partly edited, check: git -C {REPO} diff")
    if DIGEST.read_text(encoding="utf-8") == before:
        warn("the AI did not change the digest; read its answer above. If nothing needed changing, run: codebase/opencode-kit.py mark-cubi-digest-synced")
        return
    print(git(["diff", "--stat", "--", str(DIGEST)]), file=sys.stderr)
    info(f"review with: git -C {REPO} diff {DIGEST.relative_to(REPO)} ; accept with: codebase/opencode-kit.py mark-cubi-digest-synced")


def mark_synced():
    """Record that the digest now matches the checked-out KB commit."""
    commit, date = kb_head()
    record = {
        "knowledge_base": KB_URL,
        "submodule": str(KB_WIKI.relative_to(REPO)),
        "digest": str(DIGEST.relative_to(REPO)),
        "derived_from_commit": commit,
        "kb_commit_date": date,
        "derived_on": datetime.date.today().isoformat(),
    }
    write_atomic(KB_SOURCE, render(record))
    info(f"recorded: digest derived from KB {commit[:7]} ({date}) in {KB_SOURCE.relative_to(REPO)}")


if __name__ == "__main__":
    sys.exit("ERROR: library module; run codebase/opencode-kit.py")
